#!/usr/bin/env python3
"""Build the deployable public portfolio into ./site.

Only the portfolio files are copied. Studio, leads, clients and docs stay out
of the published site. The script refuses to delete a site/ folder it did not
create (it looks for the .generated marker).
"""

from pathlib import Path
import shutil
import sys

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "site"
MARKER = ".generated"

FILES = ["index.html", "robots.txt"]
DIRS = ["assets"]


def main() -> int:
    for name in FILES:
        if not (ROOT / name).exists():
            print(f"Missing required file: {name}")
            return 1
    for name in DIRS:
        if not (ROOT / name).is_dir():
            print(f"Missing required folder: {name}/")
            return 1

    if OUT.exists():
        entries = list(OUT.iterdir())
        if entries and not (OUT / MARKER).exists():
            print(f"Refusing to overwrite {OUT}: it was not created by this script.")
            print("Move it aside or delete it yourself if you are sure.")
            return 1
        shutil.rmtree(OUT)

    OUT.mkdir()
    for name in FILES:
        shutil.copy2(ROOT / name, OUT / name)
    for name in DIRS:
        shutil.copytree(ROOT / name, OUT / name, ignore=shutil.ignore_patterns(".DS_Store"))
    (OUT / MARKER).write_text("Generated by tools/build_public.py\n", encoding="utf-8")

    count = sum(1 for path in OUT.rglob("*") if path.is_file())
    print(f"Public site built in {OUT} ({count} files).")
    print("Deploy the contents of site/ — not the repository root.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
